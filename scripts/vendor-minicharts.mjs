// Copies the Minicharts kit into packages/draw/src/vendor/minicharts/kit.ts as text.
// Usage: node scripts/vendor-minicharts.mjs [path to the minicharts skill folder]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { homedir } from 'node:os';
const dir = process.argv[2] ?? join(homedir(), '.claude/skills/minicharts');
const read = (p) => readFileSync(join(dir, p), 'utf8');
const parts = { ENGINE: read('assets/engine.js'), EXAMPLES: read('assets/examples.js'), TYPES: read('references/types.md'), KIT: read('references/kit.md') };
const head = '// Vendored from Minicharts by April Zhu (https://april-zhu.com/minicharts), MIT, see ./LICENSE and ./NOTICE.md.\n// Generated by scripts/vendor-minicharts.mjs; do not edit by hand.\n';
writeFileSync('packages/draw/src/vendor/minicharts/kit.ts', head + Object.entries(parts).map(([k, v]) => `export const ${k}: string = ${JSON.stringify(v)};\n`).join(''));
console.log('kit.ts', Object.fromEntries(Object.entries(parts).map(([k, v]) => [k, v.length])));

// The two hands the drawings write in (SIL OFL 1.1, through Fontsource), held as base64 so a drawing carries its own
// letters wherever it is painted: in a picture, on a canvas, in a deck.
const font = (pkg, file) => readFileSync(join('packages/draw/node_modules/@fontsource', pkg, 'files', file)).toString('base64');
writeFileSync('packages/draw/src/vendor/fonts.ts', '// Generated by scripts/vendor-minicharts.mjs from @fontsource/gaegu and @fontsource/young-serif (SIL OFL 1.1); do not edit.\n'
  + `export const GAEGU = '${font('gaegu', 'gaegu-latin-400-normal.woff2')}';\nexport const YOUNG_SERIF = '${font('young-serif', 'young-serif-latin-400-normal.woff2')}';\n`);
